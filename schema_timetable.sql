-- ------------------------------------------------------------
-- Database-level validation: a timetable row may only use records
-- belonging to the same school, and the teacher must already be
-- assigned to both the selected class and subject.
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.validate_timetable_entry()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM public.academic_sessions WHERE id = NEW.session_id AND school_id = NEW.school_id) THEN
        RAISE EXCEPTION 'Academic session does not belong to this school';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM public.classes WHERE id = NEW.class_id AND school_id = NEW.school_id) THEN
        RAISE EXCEPTION 'Class does not belong to this school';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM public.subjects WHERE id = NEW.subject_id AND school_id = NEW.school_id) THEN
        RAISE EXCEPTION 'Subject does not belong to this school';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM public.teachers WHERE id = NEW.teacher_id AND school_id = NEW.school_id) THEN
        RAISE EXCEPTION 'Teacher does not belong to this school';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM public.teacher_classes
        WHERE teacher_id = NEW.teacher_id AND class_id = NEW.class_id
    ) THEN
        RAISE EXCEPTION 'Teacher is not assigned to the selected class in the Teacher Catalog';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM public.teacher_subjects
        WHERE teacher_id = NEW.teacher_id AND subject_id = NEW.subject_id
    ) THEN
        RAISE EXCEPTION 'Teacher is not assigned to the selected subject in the Teacher Catalog';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validate_timetable_entry
ON public.timetable_entries;

CREATE TRIGGER trg_validate_timetable_entry
BEFORE INSERT OR UPDATE ON public.timetable_entries
FOR EACH ROW
EXECUTE FUNCTION public.validate_timetable_entry();

-- ------------------------------------------------------------
-- Atomic save for the Auto Planner.
-- The whole generated timetable is inserted as one transaction.
-- If one row fails, none of the generated rows are saved.
-- ------------------------------------------------------------
DROP FUNCTION IF EXISTS public.save_timetable_batch(BIGINT, BIGINT, JSONB);

CREATE OR REPLACE FUNCTION public.save_timetable_batch(
    p_school_id BIGINT,
    p_session_id BIGINT,
    p_entries JSONB
)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_profile_school_id BIGINT;
    v_count INTEGER := 0;
    v_item JSONB;
BEGIN
    SELECT p.school_id
      INTO v_profile_school_id
    FROM public.profiles p
    WHERE p.id = auth.uid()
      AND p.role = 'admin'
    LIMIT 1;

    IF v_profile_school_id IS NULL OR v_profile_school_id <> p_school_id THEN
        RAISE EXCEPTION 'Only a school administrator can save an automatic timetable';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM public.academic_sessions
        WHERE id = p_session_id
          AND school_id = p_school_id
    ) THEN
        RAISE EXCEPTION 'Academic session does not belong to this school';
    END IF;

    IF p_entries IS NULL OR jsonb_typeof(p_entries) <> 'array' THEN
        RAISE EXCEPTION 'Timetable entries must be a JSON array';
    END IF;

    FOR v_item IN SELECT * FROM jsonb_array_elements(p_entries)
    LOOP
        INSERT INTO public.timetable_entries (
            school_id,
            session_id,
            class_id,
            subject_id,
            teacher_id,
            day_of_week,
            period_no,
            room
        )
        VALUES (
            p_school_id,
            p_session_id,
            (v_item->>'class_id')::BIGINT,
            (v_item->>'subject_id')::BIGINT,
            (v_item->>'teacher_id')::BIGINT,
            v_item->>'day_of_week',
            (v_item->>'period_no')::INTEGER,
            NULLIF(v_item->>'room', '')
        );

        v_count := v_count + 1;
    END LOOP;

    RETURN v_count;
END;
$$;

GRANT EXECUTE ON FUNCTION public.save_timetable_batch(BIGINT, BIGINT, JSONB)
TO authenticated;

REVOKE EXECUTE ON FUNCTION public.save_timetable_batch(BIGINT, BIGINT, JSONB)
FROM PUBLIC;
