-- Keep updated_at current without introducing a new global trigger.
CREATE OR REPLACE FUNCTION public.touch_timetable_entry_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_touch_timetable_entry_updated_at
ON public.timetable_entries;

CREATE TRIGGER trg_touch_timetable_entry_updated_at
BEFORE UPDATE ON public.timetable_entries
FOR EACH ROW
EXECUTE FUNCTION public.touch_timetable_entry_updated_at();

