-- ============================================================
-- S.A. KIDDIES ACADEMY SRMS
-- TIMETABLE MODULE
--
-- Uses the existing teachers / teacher_classes / teacher_subjects
-- catalog. This module stores only the actual timetable placement.
--
-- Rules enforced by the database:
--   1. A class cannot have two lessons in the same period.
--   2. A teacher cannot teach two classes in the same period.
--   3. Timetable entries belong to one academic session.
--   4. Existing teacher/class/subject records remain authoritative.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.timetable_periods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL REFERENCES public.schools(id) ON DELETE CASCADE,
    day_of_week TEXT NOT NULL CHECK (day_of_week IN ('Monday','Tuesday','Wednesday','Thursday','Friday')),
    period_no INTEGER NOT NULL CHECK (period_no > 0),
    label TEXT NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    is_break BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (school_id, day_of_week, period_no)
);

CREATE TABLE IF NOT EXISTS public.timetable_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL REFERENCES public.schools(id) ON DELETE CASCADE,
    session_id BIGINT NOT NULL REFERENCES public.academic_sessions(id) ON DELETE CASCADE,
    class_id BIGINT NOT NULL REFERENCES public.classes(id) ON DELETE CASCADE,
    subject_id BIGINT NOT NULL REFERENCES public.subjects(id) ON DELETE CASCADE,
    teacher_id BIGINT NOT NULL REFERENCES public.teachers(id) ON DELETE CASCADE,
    day_of_week TEXT NOT NULL CHECK (day_of_week IN ('Monday','Tuesday','Wednesday','Thursday','Friday')),
    period_no INTEGER NOT NULL CHECK (period_no > 0),
    room TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (school_id, session_id, class_id, day_of_week, period_no),
    UNIQUE (school_id, session_id, teacher_id, day_of_week, period_no)
);

CREATE INDEX IF NOT EXISTS idx_timetable_entries_school_session
    ON public.timetable_entries(school_id, session_id);
CREATE INDEX IF NOT EXISTS idx_timetable_entries_class
    ON public.timetable_entries(class_id, session_id);
CREATE INDEX IF NOT EXISTS idx_timetable_entries_teacher
    ON public.timetable_entries(teacher_id, session_id);

ALTER TABLE public.timetable_periods ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.timetable_entries ENABLE ROW LEVEL SECURITY;

